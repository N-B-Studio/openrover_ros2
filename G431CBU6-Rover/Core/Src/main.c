/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_USART1_UART_Init();
  MX_USB_Device_Init();
  /* USER CODE BEGIN 2 */
  /* 安全默认状态：两侧方向固定，PWM先为0 */
  HAL_GPIO_WritePin(DIR_L_GPIO_Port, DIR_L_Pin, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(DIR_R_GPIO_Port, DIR_R_Pin, GPIO_PIN_RESET);

  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 0U);
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, 0U);

  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_2);

  /* 给PC一些USB枚举时间 */
  HAL_Delay(1500U);

  Debug_Print(
      "\r\n"
      "STM32G431 ROS car minimal POC\r\n"
      "SYSCLK=170MHz\r\n"
      "TIM2_CH1=25kHz dimming PWM\r\n"
      "USART1=115200 8N1\r\n");
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	    char message[96];

	    /*
	     * PA0/TIM2_CH1：
	     * 0...6799循环，输出25kHz，改变占空比。
	     */
	    Set_TestPwm(pwm_compare);

	    pwm_compare =
	        (uint32_t)((int32_t)pwm_compare + pwm_step);

	    if (pwm_compare >= 6799U)
	    {
	        pwm_compare = 6799U;
	        pwm_step = -20;
	    }
	    else if (((int32_t)pwm_compare <= 0) && (pwm_step < 0))
	    {
	        pwm_compare = 0U;
	        pwm_step = 20;
	    }

	    /*
	     * PC13板载LED作为heartbeat。
	     * 很多G431小板的LED是低电平点亮，
	     * Toggle不受有效电平影响。
	     */
	    static uint32_t heartbeat_count = 0U;
	    heartbeat_count++;

	    if (heartbeat_count >= 50U)
	    {
	        heartbeat_count = 0U;
	        HAL_GPIO_TogglePin(LED_GPIO_Port, LED_Pin);

	        uint32_t duty_percent =
	            (pwm_compare * 100U) / 6799U;

	        snprintf(
	            message,
	            sizeof(message),
	            "POC alive | TIM2_CH1 duty=%lu%%\r\n",
	            (unsigned long)duty_percent);

	        Debug_Print(message);
	    }

	    HAL_Delay(10U);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

